// debug_controller.ts — 调试控制台
// 独立节点图，游戏开始时创建「元件7」实体（翻开的书籍）
// 通过选项卡组件控制 Ball_Debug视觉的暂停/单步/恢复
/* eslint-disable @typescript-eslint/no-unsafe-argument */

import { g } from 'genshin-ts-touyu/runtime/core'

// ============================================================
// Graph 1: Debug_创建控制台 (ID 1073742445, 挂载足球实体)
// 职责：游戏开始时创建调试控制台实体（元件7）
// ============================================================

g.server({
  id: 1073742445,
  name: 'Debug_创建控制台',
  lang: 'zh',
  variables: {
    _init: false
  }
})
  .on('实体创建时', (_evt, f) => {
    if (f.获取节点图变量自动类型推断('_init')) {
      return
    }
    f.设置节点图变量自动类型推断('_init', true)

    // 在「地图中心偏左、高度 2」创建元件7
    f.创建元件(
      prefabId(1077936280),           // 元件7（翻开的书籍）
      f.创建三维向量(-3.0, 2.0, 0.0), // 位置：中心偏左，高度=2
      f.创建三维向量(0.0, 0.0, 0.0),  // 旋转：默认朝向
      self,                            // 拥有者：足球实体
      false,                           // 不覆写等级
      0n,                              // 等级
      list('int', [])                  // 无单位标签
    )
  })

// ============================================================
// Graph 2: Debug_选项卡控制 (ID 1073742446, 挂载元件7实体)
// 职责：响应选项卡选中，控制 Ball_Debug 单步/恢复
//
//  选项卡 0 → 单步执行
//  选项卡 1 → 恢复运行
//
// 在编辑器中：
//   1. 给元件7（prefabId 1077936280）添加选项卡组件
//   2. 选项卡 0 文字："单步执行"
//   3. 选项卡 1 文字："恢复运行"
//   4. 将此节点图 (ID 1073742446) 挂载到元件7
// ============================================================

g.server({
  id: 1073742446,
  name: 'Debug_选项卡控制',
  lang: 'zh'
})
  .on('选项卡选中时', (evt, f) => {
    // 查找足球实体
    const balls = f.获取场上指定元件ID的实体(prefabId(1077936262))
    const ball = balls[0]

    if (bool(evt.tabId == 1n)) {
      // 选项卡 0：单步执行
      f.设置自定义变量(ball, '_debugFlash0', 1.0, true)
    } else if (bool(evt.tabId == 2n)) {
      // 选项卡 1：恢复运行
      f.设置自定义变量(ball, '_debugFlash1', 1.0, true)
    }
  })
